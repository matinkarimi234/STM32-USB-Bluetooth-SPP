#ifndef BT_F746_FLASH_LAYOUT_H
#define BT_F746_FLASH_LAYOUT_H
/* F746 bank-1 erase geometry. The port also checks the physical flash-size fuse.
 * The chosen complete sector MUST be reserved by the consuming linker project. */
#ifndef BT_BONDS_FLASH_START
#error Define BT_BONDS_FLASH_START before including the F746 layout
#endif
#if BT_BONDS_FLASH_START == 0x08000000UL
#define BT_F746_BOND_SECTOR 0U
#define BT_F746_BOND_SECTOR_BYTES 0x00008000UL
#elif BT_BONDS_FLASH_START == 0x08008000UL
#define BT_F746_BOND_SECTOR 1U
#define BT_F746_BOND_SECTOR_BYTES 0x00008000UL
#elif BT_BONDS_FLASH_START == 0x08010000UL
#define BT_F746_BOND_SECTOR 2U
#define BT_F746_BOND_SECTOR_BYTES 0x00008000UL
#elif BT_BONDS_FLASH_START == 0x08018000UL
#define BT_F746_BOND_SECTOR 3U
#define BT_F746_BOND_SECTOR_BYTES 0x00008000UL
#elif BT_BONDS_FLASH_START == 0x08020000UL
#define BT_F746_BOND_SECTOR 4U
#define BT_F746_BOND_SECTOR_BYTES 0x00020000UL
#elif BT_BONDS_FLASH_START == 0x08040000UL
#define BT_F746_BOND_SECTOR 5U
#define BT_F746_BOND_SECTOR_BYTES 0x00040000UL
#elif BT_BONDS_FLASH_START == 0x08080000UL
#define BT_F746_BOND_SECTOR 6U
#define BT_F746_BOND_SECTOR_BYTES 0x00040000UL
#elif BT_BONDS_FLASH_START == 0x080C0000UL
#define BT_F746_BOND_SECTOR 7U
#define BT_F746_BOND_SECTOR_BYTES 0x00040000UL
#else
#error BT_BONDS_FLASH_START must be an exact STM32F746 flash-sector boundary
#endif
#endif
